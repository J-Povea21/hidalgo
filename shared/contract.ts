/**
 * The contract between the workbench server and its page. Both import this
 * file; it imports nothing of ours. A field renamed here breaks both sides
 * at compile time.
 */
import { z } from 'zod';

export const Id = z.string().min(1).max(64).regex(/^[A-Za-z0-9_-]+$/);
const Text = z.string().min(1).max(20_000);
const Short = z.string().min(1).max(300);

// ---------- item kinds: a schema per kind, a view per kind in client/kinds ----------

export const CardFields = z.object({
  title: Short,
  tags: z.array(Short).max(12).default([]),
  proposal: z.object({ priority: Short, shape: Short, status: Short, related: Short }),
  body: z.object({
    what: Text,
    where: z.array(Text).min(1).max(30),
    why: Text.optional(),
    outOfScope: Text.optional(),
    notes: Text.optional(),
  }),
  criteria: z.array(z.object({ mode: z.enum(['code', 'test']), text: Text })).max(40),
  manualQa: z.array(Text).max(20).default([]),
  assuming: z.array(Text).max(20).default([]),
  provenance: Short,
});
export type CardFields = z.infer<typeof CardFields>;

/**
 * Every kind the workbench can show. pr-review and review-queue add theirs here.
 * Every kind has a `title`: the tab, the progress bar and list_runs show it.
 */
export const ItemKinds = { card: CardFields } as const satisfies Record<string, z.ZodType<{ title: string }>>;
export type ItemKind = keyof typeof ItemKinds;
export const ItemKind = z.enum(Object.keys(ItemKinds) as [ItemKind, ...ItemKind[]]);

// ---------- questions, threads, messages ----------

export const QuestionSpec = z.object({
  text: Short,
  context: Text.optional(),
  evidence: z.array(z.object({ kind: z.enum(['verified', 'judgement']), text: Text })).max(8).default([]),
  options: z.array(z.object({ label: Short, detail: Text })).min(2).max(6),
  recommended: z.number().int().min(0),
});
export type QuestionSpec = z.infer<typeof QuestionSpec>;

export interface Answer { choice: number; note?: string; at: string }
export interface Question extends QuestionSpec { id: string; answer?: Answer }

export type ThreadOwner = { type: 'run' } | { type: 'item'; itemId: string };
export interface Thread { id: string; owner: ThreadOwner }

export interface Message {
  id: string;
  threadId: string;
  from: 'claude' | 'user';
  at: string;
  text: string;
  images?: string[];
  /** Sequence number of the page event this message answers. */
  replyTo?: number;
}

export type VerdictValue = 'approved' | 'rejected' | 'pending';
export interface Verdict { value: VerdictValue; rev: number; at: string }

interface ItemBase {
  id: string;
  rev: number;
  questions: Question[];
  threadId: string;
  verdict?: Verdict;
  /** Set by the skill once an approved item exists in the outside world (e.g. the ClickUp card). */
  done?: { at: string; note: string };
  /** Criterion edits made by the user since the last revision, by field path. */
  edits?: Record<string, string>;
}

/** An item of one kind: its fields are exactly that kind's schema output. */
export type ItemOf<K extends ItemKind> = ItemBase & { kind: K; fields: z.output<(typeof ItemKinds)[K]> };

/** Any item, discriminated by `kind`, so code that checks the kind gets typed fields without casts. */
export type Item = { [K in ItemKind]: ItemOf<K> }[ItemKind];

// ---------- diagrams: structure in, Mermaid generated by the server ----------

const NodeId = z.string().min(1).max(40).regex(/^[A-Za-z][A-Za-z0-9_]*$/);
export const DiagramSpec = z.discriminatedUnion('type', [
  z.object({
    type: z.literal('flow'),
    direction: z.enum(['LR', 'TB']).default('LR'),
    nodes: z.array(z.object({ id: NodeId, label: Short, group: NodeId.optional() })).min(1).max(40),
    groups: z.array(z.object({ id: NodeId, label: Short })).max(12).default([]),
    edges: z.array(z.object({ from: NodeId, to: NodeId, label: Short.optional(), dashed: z.boolean().default(false) })).max(80),
  }),
  z.object({
    type: z.literal('sequence'),
    participants: z.array(z.object({ id: NodeId, label: Short })).min(2).max(10),
    steps: z.array(z.union([
      z.object({ from: NodeId, to: NodeId, text: Short, reply: z.boolean().default(false) }),
      z.object({ note: Short, over: z.array(NodeId).min(1).max(2) }),
    ])).min(1).max(60),
  }),
]);
export type DiagramSpec = z.infer<typeof DiagramSpec>;
export interface Diagram { id: string; mermaid: string; outline: string }

// ---------- the run ----------

export type RunStatus = 'open' | 'paused' | 'closed';
export type Turn = 'user' | 'claude';

export interface RunState {
  id: string;
  skill: string;
  project: string;
  subject: string;
  status: RunStatus;
  startedAt: string;
  items: Item[];
  threads: Thread[];
  messages: Message[];
  diagrams: Diagram[];
  /** The live line shown while Claude works. */
  statusLine?: string;
  turn: Turn;
  /** Bumped on every change; the page re-renders when it moves. */
  version: number;
  closedOutcome?: string;
  closedAt?: string;
  /** Which thread each recorded page event came from, so replies are addressed by data. */
  eventThreads: Record<number, string>;
  /** The last logged page event already applied to this state; later ones are replayed on load. */
  appliedSeq: number;
}

// ---------- page → server events ----------

const Answers = z.record(Id, z.object({ choice: z.number().int().min(0), note: z.string().max(4000).optional() }));

export const PageEvent = z.discriminatedUnion('type', [
  z.object({ type: z.literal('answers'), itemId: Id, answers: Answers }),
  z.object({
    type: z.literal('message'),
    threadId: Id,
    text: z.string().max(20_000),
    /** data: URLs on the wire, replaced by stored file names once recorded. */
    images: z.array(z.string().max(12_000_000)).max(5).default([]),
  }),
  z.object({ type: z.literal('verdict'), itemId: Id, rev: z.number().int().min(1), value: z.enum(['approved', 'rejected', 'pending']) }),
  z.object({ type: z.literal('edit'), itemId: Id, path: z.string().max(80), text: Text }),
  z.object({ type: z.literal('diagram-failed'), diagramId: Id, error: z.string().max(2000) }),
]);
export type PageEvent = z.infer<typeof PageEvent>;

/** An event once recorded: stored images by file name, sequence number, time. */
export type RecordedEvent = (Exclude<PageEvent, { type: 'message' }> | (Omit<Extract<PageEvent, { type: 'message' }>, 'images'> & { images: string[] }))
  & { seq: number; at: string };

/** Omit that keeps a union's members apart (plain Omit merges them into one shape). */
export type DistributiveOmit<T, K extends PropertyKey> = T extends unknown ? Omit<T, K> : never;

/** A recorded event before the log gives it a sequence number. */
export type UnsequencedEvent = DistributiveOmit<RecordedEvent, 'seq'>;

// ---------- live index (the "Open reviews" switcher) ----------

export interface LiveEntry {
  runId: string;
  project: string;
  skill: string;
  subject: string;
  port: number;
  pid: number;
  /** Process start, so a reused pid is not mistaken for this server. */
  processStartedAt: string;
  heartbeat: string;
  /** Open questions plus items ready for a verdict: what the switcher shows as waiting on you. */
  pendingForUser: number;
  url: string;
  status: RunStatus;
  /** The Claude Code process that owns this server; the Stop hook matches it to its own parent. */
  ownerPid: number;
  /** Whether Claude is holding wait_for_events right now. */
  claudeListening: boolean;
}

